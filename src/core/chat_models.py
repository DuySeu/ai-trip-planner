"""The chat models a visitor may pick for a conversation, per LLM provider."""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from pathlib import Path

from core import constants

# One entry of a ModelId block, on one line or wrapped by ruff: "<id>"  # <label>
ENTRY = re.compile(r'^\s*(?:\w+ = \(?)?"([^"]+)"\s+#\s*(.+?)\s*$', re.M)


# The id -> label pairs between "# <tag>:BEGIN" and "# <tag>:END" of ModelId, in file order
def read_block(source: str, tag: str) -> dict[str, str]:
    match = re.search(
        rf"^    # {re.escape(tag)}:BEGIN\b(.*?)^    # {re.escape(tag)}:END$", source, re.S | re.M
    )
    return dict(ENTRY.findall(match.group(1))) if match else {}


# Provider -> chat model id -> label, from the provider's block in core/constants.py (OPENROUTER is
# generated by scripts/sync_models.sh, BEDROCK is written by hand); openai has none, so nothing to pick
_SOURCE = Path(constants.__file__).read_text(encoding="utf-8")
CATALOG: Mapping[str, Mapping[str, str]] = {
    "openrouter": read_block(_SOURCE, "OPENROUTER"),
    "bedrock": read_block(_SOURCE, "BEDROCK"),
}


# The provider's pickable chat models, id -> label, in catalog order
def chat_models_for(provider: str) -> Mapping[str, str]:
    return CATALOG.get(provider, {})


# The model "Auto" stands for: the first CHAT_MODELS id in the catalog, else the first catalog id
def default_chat_model(provider: str, chat_models: Sequence[str]) -> str | None:
    catalog = chat_models_for(provider)
    return next((m for m in chat_models if m in catalog), next(iter(catalog), None))
